/** Текст для кода ошибки: сообщение сервера важнее словаря, словарь — важнее кода. */
export function errorText(code, serverMessage) {
  const message = typeof serverMessage === 'string' ? serverMessage.trim() : '';
  if (message && message !== code) return message;
  return TEXTS[code] || message || 'Не удалось выполнить действие — повторите попытку.';
}

export function errorCode(error) {
  return error?.code || '';
}
